# ## 13. グラフを作るときに注意すること
# 
# グラフは、単に作ればよいというものではありません。「何を伝えたいのか」を考えて作成することが重要です。
# 
# ### ① 軸ラベルを付ける
# `plt.xlabel('時間')` `plt.ylabel('水位 (m)')` のように、何を表しているのかを明確にします。
# 
# ### ② 単位を明記する
# 土木工学では単位が非常に重要です。水位 (m)、流量 (m³/s)、雨量 (mm)、交通量 (台/h)、変位 (mm) など、適切な単位を表示します。
# 
# ### ③ タイトルを付ける
# グラフだけを見ても、何のデータなのか分かるようにします。
# 
# ### ④ 必要に応じて凡例を付ける
# 複数のデータを表示する場合は、凡例を追加します。
# 
# ### ⑤ グラフの種類を目的に合わせて選ぶ
# * 時間による変化 → 折れ線グラフ
# * 項目間の比較 → 棒グラフ
# * 2つの数値の関係 → 散布図
# 
# また、グラフを作成すること自体が目的ではなく、グラフからデータの特徴を読み取ることも重要です。雨量と河川水位をグラフ化したとき、単に「雨量が増えると水位が上がった」と結論づけるのではなく、ピークの時間差や観測地点、流域の特性なども考える必要があります。

