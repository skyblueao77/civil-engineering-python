# %% [markdown]
# ## 9. データをグループごとに集計する
#
# pandasには、同じ種類のデータをグループに分けて集計する機能もあります。
#
# 例えば、次のような交通量データがあるとします。

# %%
traffic_data = pd.DataFrame(
    {
        "曜日": ["月", "月", "火", "火", "水", "水"],
        "地点": ["A", "B", "A", "B", "A", "B"],
        "交通量": [1200, 1500, 1300, 1600, 1250, 1550]
    }
)

print(traffic_data)

# %% [markdown]
# 曜日ごとの平均交通量を求める場合は、次のようにします。

# %%
print(traffic_data.groupby("曜日")["交通量"].mean())

# %% [markdown]
# `groupby()` は「同じ値を持つ行をまとめて集計する機能」と考えるとイメージしやすいでしょう。
#
# 土木分野でも、
#
# - 地点ごとの平均交通量
# - 日ごとの平均雨量
# - 観測地点ごとの平均水位
#
# など、グループごとの集計を行う場面があります。
#
# 今回は基本的な使い方だけ紹介しましたが、`groupby()` はpandasでデータ分析を行う上で重要な機能です。
#
# ℹ️ **AIにコードを作らせたときも、以下の4点を確認する習慣をつけましょう:**
# - `shape`
# - `columns`
# - `dtypes`
# - `head()`

