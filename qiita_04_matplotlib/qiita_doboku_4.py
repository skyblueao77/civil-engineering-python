# %% [markdown]
# ## 9. 散布図を作ってみる
# 
# 散布図は、2つの数値データの関係を見るときによく使われます。
# 
# 例えば、雨量と河川水位の関係を考えてみます。`plt.scatter()` を使って作成します。

# %%
rainfall = [5, 10, 15, 20, 25, 30, 40]
water_level = [1.1, 1.2, 1.3, 1.5, 1.7, 2.0, 2.5]

plt.scatter(rainfall, water_level)

plt.title('雨量と河川水位の関係')
plt.xlabel('雨量 (mm)')
plt.ylabel('水位 (m)')

plt.grid()
plt.show()


# %% [markdown]
# このようなグラフを作ることで、「雨量が増えると水位も上昇する傾向があるか」といったデータの関係を視覚的に確認できます。
# 
# ただし、グラフから相関関係が見られたとしても、**「一方が増えたから必ずもう一方が増える」**と因果関係まで判断できるわけではありません。実際の土木データを分析するときには、統計的な検討や工学的な考察も必要になります。

