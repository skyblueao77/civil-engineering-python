# * `plt.plot()` による折れ線グラフ
# * `plt.bar()` による棒グラフ
# * `plt.scatter()` による散布図
# * `title()` によるタイトルの設定
# * `xlabel()`・`ylabel()` による軸ラベルの設定
# * `grid()` によるグリッドの表示
# * `legend()` による凡例の表示
# * `savefig()` によるグラフの保存
# * pandasとmatplotlibの組み合わせ
# * CSVから読み込んだデータの可視化
# 
# です。
# 
# 前回学んだpandasでは、データを**「整理する・抽出する・集計する」**ことを学びました。今回のmatplotlibでは、そのデータを**「グラフにして見る」**方法を学びました。
# 
# この2つを組み合わせることで、
# 
# ```text
# 表データ → pandas → データの整理・集計 → matplotlib → グラフによる可視化
# ```
# 
# というデータ分析の基本的な流れを作ることができます。
# 
# 土木分野では、雨量、水位、流量、交通量、地盤、構造物など、さまざまなデータを扱います。これらのデータを単に数値として見るだけでなく、グラフとして可視化することで、データの変化や特徴をより直感的に把握できるようになります。
# 
# また、生成AIを利用すれば、matplotlibのコードを一から書かなくても、目的に応じたコードを生成してもらうことができます。しかし、グラフの種類は適切か、軸は正しいか、単位は正しいか、データの扱い方は適切か、グラフから何が読み取れるか、その結果は土木工学的に妥当か、を判断するためには、基本的な知識が必要です。
# 
# これからのPython学習では、**「すべてのコードを自分で書く」**ことだけを目標にするのではなく、**「AIやライブラリを活用しながら、生成されたコードと結果を理解・検証できる」**ことも重要になっていくでしょう。
