# * `plt.ylabel()` → 縦軸のラベル
# 
# 特に土木工学では、単位が重要になります。例えば、水位 (m)、流量 (m³/s)、交通量 (台/h)、変位 (mm)、応力 (MPa) など、必要に応じて単位を明記しましょう。

# %%
