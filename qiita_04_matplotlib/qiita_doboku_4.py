# 特に土木分野では、単にPythonコードが実行できればよいわけではありません。水位の単位がmなのかcmなのか、流量の単位がm³/sなのかL/sなのか、交通量が台/hなのか台/日なのかを間違えるだけでも、結果の意味が大きく変わります。
