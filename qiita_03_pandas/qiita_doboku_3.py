# ## 3. DataFrameを作ってみる
#
# まずは簡単な水門データを作成してみます。

# %%

gate_data = pd.DataFrame(
    {
        "水門": ["A", "B", "C"],
        "開度(m)": [1.2, 2.0, 1.5],
        "流量(m3/s)": [32, 55, 40]
    }
)

print(gate_data)

# %% [markdown]
# この表のようなデータ構造を **DataFrame** と呼びます。
#
# DataFrameには列名（カラム名）があり、今回の例では
#
# - 水門
# - 開度(m)
# - 流量(m3/s)
#
# が列名にあたります。
#
# ### DataFrameとSeries
#
# pandasでは、表全体を **DataFrame** と呼びます。
#
# 一方、DataFrameから1つの列を**Series**として取り出すことができます。
# イメージ図↓
# ```txt
# DataFrame（表全体）
#
# | 水門 | 開度(m) | 流量(m3/s) |
# |------|---------|-----------|
# | A    | 1.2     | 32        |
# | B    | 2.0     | 55        |
# | C    | 1.5     | 40        |
#
# ↓ 流量列を取り出す
#
# Series
#
# 0    32
# 1    55
# 2    40
# ```
# このように、DataFrameは複数のSeriesから構成されています。
#
# 例えば、

# %%
print(gate_data["流量(m3/s)"])

# %% [markdown]
# とすると、「流量(m3/s)」という1列だけを取り出すことができます。
#
# このような1次元のデータが`Series`です。
#
# イメージとしては、
#
# - DataFrame → 表全体
# - Series → 表の1列
#
# と考えておくと分かりやすいでしょう。
#
# pandasでは、このDataFrameとSeriesを使ってデータを操作していきます。

# %% [markdown]
# ## 4. 平均流量を求める
#
# 流量の平均値を計算してみます。

# %%
print(gate_data["流量(m3/s)"].mean())

# %% [markdown]
# 平均流量は約42.3m³/sであることが分かります。
#
# ----

# %% [markdown]
# ## 5. 最大流量を求める
#
# 最大値も簡単に計算できます。

# %%
print(gate_data["流量(m3/s)"].max())

# %% [markdown]
# 最大流量は55m³/sです。
#
# ----

# %% [markdown]
# ## 6. 条件に合うデータを探す
#
# 流量が40m³/sを超える水門だけを表示してみます。

# %%
result = gate_data[gate_data["流量(m3/s)"] > 40]

print(result)

# %% [markdown]
# このように条件に基づいてデータを抽出できます。
#
# ### 必要な列だけを取り出す
#
# 例えば、「流量が40m³/sを超える水門について、水門名と流量だけを表示したい」とします。

# %%
result = gate_data.loc[
    gate_data["流量(m3/s)"] > 40,
    ["水門", "流量(m3/s)"]
]

print(result)

# %% [markdown]
# locを使うと、条件に合う行だけでなく、表示したい列も指定できます。
# locの基本形は
#
# ```python
# df.loc[行条件, 列名]
# ```
#
# です。
#
# 左側で**行**を指定し、右側で**列**を指定します。
# このように、pandasでは必要なデータだけを取り出して分析することができます。

# %% [markdown]
# ## 7. CSVファイルを読み込む
