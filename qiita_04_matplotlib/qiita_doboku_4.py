# ## 3. 折れ線グラフを作ってみる
# 
# まずは、最も基本的なグラフの一つである折れ線グラフを作ってみます。
# 
# 例えば、1週間の河川水位を考えてみます。

# %%
days = ['月', '火', '水', '木', '金', '土', '日']
