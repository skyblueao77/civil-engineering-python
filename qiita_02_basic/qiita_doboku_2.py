# ==========================================
# 1. 変数
# ==========================================
# 変数とは、データを保存しておくための箱のようなものです。
# （Pythonでは厳密には「オブジェクトへの参照」となります）

# 参照の例
a = [1, 2, 3]
b = a
b[0] = 4
print("--- 1. 変数 (参照の例) ---")
print(a)  # [4, 2, 3] と出力される

# 橋の長さを代入して表示
bridge_length = 120
print("橋の長さ:", bridge_length)


# ==========================================
# 2. データ型
# ==========================================
print("\n--- 2. データ型 ---")

# 整数 (int)
traffic_count = 1500
print("交通量 (int):", traffic_count)

# 小数 (float)
river_width = 25.6
print("川幅 (float):", river_width)

# 文字列 (str)
city_name = "Kobe"
print("都市名 (str):", city_name)

# 真偽値 (bool)
is_safe = True
print("安全性フラグ (bool):", is_safe)


# ==========================================
# 3. 四則演算
# ==========================================
print("\n--- 3. 四則演算 ---")

a = 10
b = 5
print("足し算:", a + b)
print("引き算:", a - b)
print("掛け算:", a * b)
print("割り算:", a / b)

# 土木例：道路延長の計算
road1 = 120
road2 = 80
total = road1 + road2
print("道路の総延長:", total)


# ==========================================
# 4. 条件分岐
# ==========================================
print("\n--- 4. 条件分岐 ---")

# if文
rainfall = 120
if rainfall > 100:
    print("大雨に注意")

# if - else文
rainfall = 50
if rainfall > 100:
    print("大雨に注意")
else:
    print("通常")


# ==========================================
# 5. 繰り返し処理
# ==========================================
print("\n--- 5. 繰り返し処理 ---")

# 基本的なfor文
for i in range(5):
    print(i)

# 土木例：5地点の測定データ（水深など）を順番に表示
print("地点ごとの水深データ:")
depth = [1.2, 1.5, 1.8, 2.0, 1.7]
for d in depth:
    print(d)


# ==========================================
# 6. リスト
# ==========================================
print("\n--- 6. リスト ---")

population = [1000, 1200, 1500]
print("人口データリスト:", population)


# ==========================================
# 7. 簡単な演習
# ==========================================
print("\n--- 7. 簡単な演習 ---")

# 3地点の交通量データの合計値を計算
traffic = [1200, 1500, 1800]
total = 0
for t in traffic:
    total += t

print("交通量の合計値:", total)


