# ## 1. pandasとは
#
# pandasは、表形式のデータを効率よく扱うためのPythonライブラリです。
#
# Excelのような表データをPythonから読み込んだり、検索したり、集計したりすることができます。
#
# 例えば、土木分野では次のようなデータを扱うことがあります。
#
# - 水門の開度や流量
# - 河川の水位
# - 雨量
# - 交通量
# - 地盤調査結果
# - 人口統計
# - 気象観測データ
#
# これらのデータは、多くの場合「行」と「列」を持つ表形式になっています。
#
# 例えば、次のような水門データを考えてみます。
#
# | 水門 | 開度(m) | 流量(m3/s) |
# | -- | ----- | -------- |
# | A  | 1.2   | 32       |
# | B  | 2.0   | 55       |
# | C  | 1.5   | 40       |
#
# このようなデータについて、
#
# - 平均流量を求める
# - 最大流量を調べる
# - 流量が一定値を超える水門を探す
# - 必要な列だけを取り出す
# - CSVファイルから大量のデータを読み込む
#
# といった処理を、pandasを使うことで簡単に行えるようになります。
#
# pandasを使うメリットは、単に大量のデータを扱えることだけではありません。条件による抽出、集計、並べ替え、欠測値の処理、データの結合など、データ分析で頻繁に行う処理を比較的少ないコードで実行できます。(近年`Polars`などのライブラリも使われるようになってきていますが、現時点ではpandasが最も普及しているため、本シリーズではpandasを扱います。)
